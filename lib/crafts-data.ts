export function getCraftName(craft: CraftCategory, lang: Language): string {
  if (lang === 'te') return `${craft.nameTe} (${craft.nameEn})`;
  if (lang === 'hi') return `${craft.nameHi} (${craft.nameEn})`;
  return craft.nameEn;
}

export function getCraftTagline(craft: CraftCategory, lang: Language): string {
  if (lang === 'te') return craft.taglineTe;
  if (lang === 'hi') return craft.taglineHi;
  return craft.taglineEn;
}
